import type { EventTicketCategory, EventTicketProvider } from '@lib/database/Types';
import type { FinancialFilter } from '@lib/tickets/Types';
import type { ProviderProduct } from './Types';
import { createTicketServiceForProvider } from '@lib/tickets';
import db, { tEvents, tEventsTicketsConfiguration } from '@lib/database';

import { kEventTicketProvider } from '@lib/database/Types';

/**
 * Information about sales on a specific day.
 */
interface DailySales {
    /**
     * Number of paid tickets sold on this day.
     */
    paid: number;

    /**
     * Number of complimentary tickets issued on this day.
     */
    complimentary: number;
}

/**
 * Sale product that exists for an event with precomputed totals and daily sales breakdown.
 */
export interface FinancialProduct {
    /**
     * Unique ID of this product as it exists in the database.
     */
    id: number;

    /**
     * Category of sale that this product belongs to.
     */
    category: EventTicketCategory;

    /**
     * Maximum number of products that can be sold.
     */
    limit?: number;

    /**
     * Price, in local currency, for which this product is being sold. Expected to remain fixed.
     */
    price?: number;

    /**
     * Name of the product that this object describes.
     */
    product: string;

    /**
     * Optional AnPlan program association that exists for this product.
     */
    program: {
        /**
         * Unique ID of the program entry, as it exists in AnPlan.
         */
        id?: number;

        /**
         * Title of the program, as it exists in AnPlan.
         */
        title?: string;
    };

    /**
     * Keyed by number of days until the event [365, 0], and valued with the daily sales counts.
     */
    sales: Map<number, DailySales>;

    /**
     * Total number of paid sales.
     */
    paidSales: number;

    /**
     * Total number of complimentary tickets issued.
     */
    complimentarySales: number;

    /**
     * Total number of sales (both paid and complimentary).
     */
    totalSales: number;

    /**
     * Total revenue generated by this product, strictly computed from paid sales.
     */
    totalRevenue: number;
}

/**
 * Interface defining the raw representation of financial data associated with a specific event.
 */
interface FinancialEventData {
    /**
     * Unique ID identifying this event.
     */
    id: number;

    /**
     * URL-safe slug identifying this event.
     */
    slug: string;

    /**
     * Short name that can be used to help refer to the event.
     */
    shortName: string;

    /**
     * Time and date, in UTC, at which the event will start.
     */
    startTime: Temporal.ZonedDateTime;

    /**
     * Time and date, in UTC, at which the event will finish.
     */
    endTime: Temporal.ZonedDateTime;

    /**
     * Sale products that exist for this event. Keyed by the product's unique ID.
     */
    products: Map<number, FinancialProduct>;
}

/**
 * Interface defining the raw representation of our financial data.
 */
export interface FinancialData {
    /**
     * Ticketing provider backing the highlighted event.
     */
    provider: EventTicketProvider;

    /**
     * External event identifier on `provider` backing the highlighted event.
     */
    providerEventId: number | string;

    /**
     * Reference date that indicates the end of the financial coverage of this event.
     */
    referenceDate: Temporal.ZonedDateTime;

    /**
     * Number of days remaining for the financial coverage of this event.
     */
    remaining: number;

    /**
     * Financial information about the selected events. The first entry in this array always is the
     * event that is being highlighted, where the remaining entries contain historical data.
     */
    data: FinancialEventData[];
}

/**
 * Raw database row selected for the target and historic events.
 */
interface RawEventRow {
    id: number;
    slug: string;
    shortName: string;
    startTime: Temporal.ZonedDateTime;
    endTime: Temporal.ZonedDateTime;
    provider?: EventTicketProvider;
    weeztixGuid?: string;
    ytpEventId?: number;
}

/**
 * Event record resolved to its single configured ticketing provider, discarding any integration
 * identifiers belonging to other providers.
 */
type ConfiguredEvent =
    | {
        id: number;
        slug: string;
        shortName: string;
        startTime: Temporal.ZonedDateTime;
        endTime: Temporal.ZonedDateTime;
        provider: typeof kEventTicketProvider.Weeztix;
        providerEventId: string;
    }
    | {
        id: number;
        slug: string;
        shortName: string;
        startTime: Temporal.ZonedDateTime;
        endTime: Temporal.ZonedDateTime;
        provider: typeof kEventTicketProvider.YourTicketProvider;
        providerEventId: number;
    };

/**
 * Number of historic events that should be considered by the processor.
 */
const kHistoricEventCount = 3;

/**
 * Maximum number of days prior to an event's end date tracked in daily sales buckets.
 */
const kSalesWindowDays = 365;

/**
 * Fetches financial data from the database for the given `eventSlug`, as well as a number of
 * historic events defined in the `kHistoricEventCount` constant (omitted when `filter` is active).
 * Returns `undefined` when the `eventSlug` has no financial information associated with it (yet).
 */
export async function fetchFinancialData(eventSlug: string, filter?: FinancialFilter)
    : Promise<FinancialData | undefined>
{
    const dbInstance = db;

    const rawTargetEvent = await dbInstance.selectFrom(tEvents)
        .where(tEvents.eventSlug.equals(eventSlug))
        .select({
            id: tEvents.eventId,
            slug: tEvents.eventSlug,
            shortName: tEvents.eventShortName,
            startTime: tEvents.eventStartTime,
            endTime: tEvents.eventEndTime,
            provider: tEvents.ticketsProvider,
            weeztixGuid: tEvents.eventWeeztixGuid,
            ytpEventId: tEvents.eventYtpEventId,
        })
        .executeSelectNoneOrOne();

    const targetEvent = rawTargetEvent ? resolveConfiguredEvent(rawTargetEvent) : undefined;
    if (!targetEvent || !(await hasEventSales(targetEvent)))
        return undefined;

    const isFiltered = Boolean(filter?.utmSource || filter?.utmCampaign);
    const historicEvents = isFiltered ? [] : await fetchHistoricEvents(targetEvent);

    const financialEventData: FinancialEventData[] = [
        await buildFinancialEventData(targetEvent, filter),
    ];

    for (const event of historicEvents)
        financialEventData.push(await buildFinancialEventData(event));

    const remaining = targetEvent.endTime.since(Temporal.Now.zonedDateTimeISO('UTC'), {
        largestUnit: 'days',
    });

    return {
        provider: targetEvent.provider,
        providerEventId: targetEvent.providerEventId,
        referenceDate: targetEvent.endTime,
        remaining: Math.max(0, Math.min(remaining.days, kSalesWindowDays)),
        data: financialEventData,
    };
}

/**
 * Resolves a raw database event row to its single active ticketing provider, ignoring any columns
 * belonging to non-selected providers.
 */
function resolveConfiguredEvent(row: RawEventRow): ConfiguredEvent | undefined {
    switch (row.provider) {
        case kEventTicketProvider.Weeztix:
            if (!row.weeztixGuid)
                return undefined;

            return {
                id: row.id,
                slug: row.slug,
                shortName: row.shortName,
                startTime: row.startTime,
                endTime: row.endTime,
                provider: kEventTicketProvider.Weeztix,
                providerEventId: row.weeztixGuid,
            };

        case kEventTicketProvider.YourTicketProvider:
            if (!row.ytpEventId)
                return undefined;

            return {
                id: row.id,
                slug: row.slug,
                shortName: row.shortName,
                startTime: row.startTime,
                endTime: row.endTime,
                provider: kEventTicketProvider.YourTicketProvider,
                providerEventId: row.ytpEventId,
            };

        default:
            return undefined;
    }
}

/**
 * Returns whether the given `event` has at least one recorded sale in its configured provider's
 * tables.
 */
async function hasEventSales(event: ConfiguredEvent): Promise<boolean> {
    const service = createTicketServiceForProvider(event.provider, event.providerEventId);
    return service ? await service.hasSales() : false;
}

/**
 * Fetches up to `kHistoricEventCount` previous events that concluded on or before `targetEvent` and
 * have categorised ticket configurations matching their single configured ticketing provider.
 */
async function fetchHistoricEvents(targetEvent: ConfiguredEvent): Promise<ConfiguredEvent[]> {
    const hasConfiguredWeeztixTickets =
        tEvents.ticketsProvider.equals(kEventTicketProvider.Weeztix)
            .and(tEvents.eventWeeztixGuid.isNotNull())
            .and(tEventsTicketsConfiguration.eventTicketWeeztixGuid.isNotNull());

    const hasConfiguredYourTicketProviderTickets =
        tEvents.ticketsProvider.equals(kEventTicketProvider.YourTicketProvider)
            .and(tEvents.eventYtpEventId.isNotNull())
            .and(tEventsTicketsConfiguration.eventTicketYtpId.isNotNull());

    const rows = await db.selectFrom(tEvents)
        .innerJoin(tEventsTicketsConfiguration)
            .on(tEventsTicketsConfiguration.eventId.equals(tEvents.eventId))
                .and(tEventsTicketsConfiguration.eventTicketCategory.isNotNull())
        .where(tEvents.eventEndTime.lessOrEqual(targetEvent.endTime))
            .and(tEvents.eventId.notEquals(targetEvent.id))
            .and(hasConfiguredWeeztixTickets.or(hasConfiguredYourTicketProviderTickets))
        .select({
            id: tEvents.eventId,
            slug: tEvents.eventSlug,
            shortName: tEvents.eventShortName,
            startTime: tEvents.eventStartTime,
            endTime: tEvents.eventEndTime,
            provider: tEvents.ticketsProvider,
            weeztixGuid: tEvents.eventWeeztixGuid,
            ytpEventId: tEvents.eventYtpEventId,
        })
        .groupBy(tEvents.eventId)
        .orderBy(tEvents.eventEndTime, 'desc')
        .limit(kHistoricEventCount)
        .executeSelectMany();

    const historicEvents: ConfiguredEvent[] = [];
    for (const row of rows) {
        const resolved = resolveConfiguredEvent(row);
        if (resolved)
            historicEvents.push(resolved);
    }

    return historicEvents;
}

/**
 * Fetches configured products from the ticketing provider configured on `event` and builds its
 * `FinancialEventData` record.
 */
async function buildFinancialEventData(event: ConfiguredEvent, filter?: FinancialFilter)
    : Promise<FinancialEventData>
{
    const rawProducts = await fetchEventProducts(event, filter);

    const products = new Map<number, FinancialProduct>();
    for (const rawProduct of rawProducts)
        products.set(rawProduct.id, buildFinancialProduct(rawProduct, event.endTime));

    return {
        id: event.id,
        slug: event.slug,
        shortName: event.shortName,
        startTime: event.startTime,
        endTime: event.endTime,
        products,
    };
}

/**
 * Dispatches product and sales retrieval to the single ticketing provider configured for `event`.
 */
async function fetchEventProducts(event: ConfiguredEvent, filter?: FinancialFilter)
    : Promise<ProviderProduct[]>
{
    const service = createTicketServiceForProvider(event.provider, event.providerEventId);
    return service ? await service.fetchFinancialProducts(event.id, filter) : [];
}

/**
 * Aggregates raw daily provider sales into a `FinancialProduct` with `[kSalesWindowDays, 0]` daily
 * buckets, total sales counts, and paid revenue relative to `eventEndTime`.
 */
function buildFinancialProduct(
    product: ProviderProduct, eventEndTime: Temporal.ZonedDateTime): FinancialProduct
{
    const eventEndDate = eventEndTime.withTimeZone('UTC').toPlainDate();

    const sales = new Map<number, DailySales>();
    for (let days = kSalesWindowDays; days >= 0; --days)
        sales.set(days, { paid: 0, complimentary: 0 });

    let paidSales = 0;
    let complimentarySales = 0;

    for (const sale of product.sales) {
        const daysUntilEvent = eventEndDate.since(Temporal.PlainDate.from(sale.date), {
            largestUnit: 'days',
        }).days;

        const clampedDays = Math.max(0, Math.min(daysUntilEvent, kSalesWindowDays));
        const entry = sales.get(clampedDays)!;

        if (sale.complimentary) {
            entry.complimentary += sale.count;
            complimentarySales += sale.count;
        } else {
            entry.paid += sale.count;
            paidSales += sale.count;
        }
    }

    return {
        id: product.id,
        category: product.category,
        limit: product.limit,
        price: product.price,
        product: product.product,
        program: product.program,
        sales,
        paidSales,
        complimentarySales,
        totalSales: paidSales + complimentarySales,
        totalRevenue: paidSales * (product.price ?? 0),
    };
}
